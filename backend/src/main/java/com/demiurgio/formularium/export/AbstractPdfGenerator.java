package com.demiurgio.formularium.export;

import com.demiurgio.formularium.dto.ValidationRequest;
import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Font;
import com.lowagie.text.Paragraph;
import com.lowagie.text.pdf.PdfWriter;

import java.io.ByteArrayOutputStream;

public abstract class AbstractPdfGenerator {

    protected final Font titleFont = new Font(Font.HELVETICA, 18, Font.BOLD);
    protected final Font headerFont = new Font(Font.HELVETICA, 12, Font.BOLD);
    protected final Font bodyFont = new Font(Font.HELVETICA, 10, Font.NORMAL);

    public byte[] generate(ValidationRequest request) throws DocumentException {
        Document document = new Document();
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        PdfWriter.getInstance(document, out);

        document.open();
        addHeader(document, request);
        addBody(document, request); // The abstract hook
        addFooter(document);
        document.close();

        return out.toByteArray();
    }

    private void addHeader(Document document, ValidationRequest request) throws DocumentException {
        document.add(new Paragraph("FORMULARIUM WORKSPACE", headerFont));
        document.add(new Paragraph("Product Information File (PIF)", titleFont));
        document.add(new Paragraph("Project: " + request.profileId(), bodyFont));
        document.add(new Paragraph(" ")); // Spacer
    }

    protected abstract void addBody(Document document, ValidationRequest request) throws DocumentException;

    private void addFooter(Document document) throws DocumentException {
        document.add(new Paragraph(" "));
        document.add(new Paragraph("Generated by Formularium Enterprise System", new Font(Font.HELVETICA, 8, Font.ITALIC)));
    }
}